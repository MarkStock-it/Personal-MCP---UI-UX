/**
 * The conclusion gate — the closing paragraph, checked against the mission's own record.
 *
 * Every other part of a mission is checked: each quote is re-read from the file, each proposed edit is
 * placed against the file as it is now, and a claim that fails either goes back once. The one part that
 * was never checked is the paragraph at the top: the leader's own summary. It is also the part a reader
 * actually acts on, and the failure it invites is specific and measurable — a summary that asserts a
 * finding the gate deleted (or a file that does not exist) while the dossier three sections below says
 * that finding was rejected. The audit literature on cited generation is exactly this: only 51.5% of
 * generated sentences were fully supported by their citations in one study of four systems
 * (Liu, Zhang & Liang, https://arxiv.org/html/2304.09848v2), and citation errors by LLMs are most
 * dangerous when the prose around them reads as confident (Walters & Wilder, "Fabrication and errors in
 * the bibliographic citations generated by ChatGPT", https://www.nature.com/articles/s41598-023-41032-5).
 *
 * So this gate does for the prose what the citation gate does for the findings, with the two things that
 * can be decided without a reader:
 *   - Does a sentence assert a finding this mission itself deleted (or one its own worker withdrew), or
 *     state as established a quote that was labelled THIN SUPPORT? One-sided matching, the same content
 *     words and stems the support label uses: the sentence has to share most of the claim's wording.
 *   - Does it name a file that is not in this repository — not in the index and not on disk?
 *
 * Two boundaries are deliberate, because a gate that cries wolf gets ignored:
 *   - `unverified` is exempt from the assertion check. By contract that field is where a rejected finding
 *     is carried as something to check, and flagging it there would punish the honest move.
 *   - A hedged sentence is not an assertion. "The claim that X was rejected by the server and is carried
 *     as unverified" restates the record; "X is fixed" repeats the deleted finding. The verb matters, and
 *     the hedge list below is what this server can tell apart deterministically.
 *
 * Nothing here decides whether a conclusion is *right*. A sentence built only from verified findings can
 * still be a bad conclusion. This checks the half that has an answer: whether the paragraph contradicts
 * the record this same run produced, at the level of a sentence that can be sent back.
 */
import fs from "node:fs/promises";
import path from "node:path";
import type { RepoIndex } from "../codebase/store.js";
import type { RepairRound } from "./repair.js";
import type { Synthesis } from "./roles.js";
import { contentWords, normalise, shareStem, type CheckedClaim, type Verification } from "./verify.js";

/** The fields of the closing paragraph that are prose, and whether they are meant to assert something. */
export type ConclusionField = "answer" | "risks" | "unverified" | "firstAction" | "definitionOfDone";
const ASSERTIVE: ConclusionField[] = ["answer", "risks", "firstAction", "definitionOfDone"];
const ALL_FIELDS: ConclusionField[] = [...ASSERTIVE, "unverified"];

export type ConclusionKind = "reintroduced-rejection" | "withdrawn-claim" | "thin-support" | "unknown-file";

export interface ConclusionIssue {
  /** 1-based position in the list the repair pass is handed, so an answer can name it by number. */
  index: number;
  field: ConclusionField;
  /** Which element of an array field, and which sentence inside it: enough to put a fix back in place. */
  item: number;
  sentence: number;
  text: string;
  kind: ConclusionKind;
  /** What the mission's own record says instead. Quoted back in the dossier and in the repair prompt. */
  because: string;
  path?: string;
  lines?: [number, number];
}

/**
 * Sentences, split on line breaks and on sentence enders. Deterministic on purpose: a repair answers by
 * number, so the numbering the prompt shows and the numbering the patch uses have to be the same one.
 */
export function splitSentences(text: string): string[][] {
  return text
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.split(/(?<=[.!?;:])\s+(?=[A-Z0-9"'([\-*])/).map((s) => s.trim()).filter(Boolean));
}

/** The fields of a synthesis, as `field`/`item` pairs, so sentences can be addressed without ambiguity. */
function fieldTexts(s: Synthesis): { field: ConclusionField; item: number; text: string }[] {
  const out: { field: ConclusionField; item: number; text: string }[] = [
    { field: "answer", item: 0, text: s.answer },
    { field: "firstAction", item: 0, text: s.firstAction },
  ];
  for (const f of ["risks", "unverified", "definitionOfDone"] as const) s[f].forEach((text, item) => out.push({ field: f, item, text }));
  return out;
}

/**
 * A sentence that marks the thing it mentions as doubted is restating the record, not asserting the
 * deleted finding. Kept as substrings of the lowercased sentence, and kept explicit so the rule is
 * readable rather than a model's judgement.
 */
const HEDGES = [
  "unverified",
  "not verified",
  "could not verify",
  "could not be verified",
  "cannot verify",
  "can't verify",
  "not established",
  "not proven",
  "unproven",
  "unconfirmed",
  "not confirmed",
  "could not confirm",
  "cannot confirm",
  "no evidence",
  "rejected",
  "was deleted",
  "not found",
  "unchecked",
  "unknown",
  "not checkable",
  "needs checking",
  "worth checking",
  "to be checked",
  "as something to check",
  "rather than guessed",
  "not supported",
  "does not support",
  "nothing confirms",
  "may not",
  "might not",
  "cannot be said",
  "no such",
];

const hedged = (sentence: string): boolean => {
  const t = sentence.toLowerCase();
  return HEDGES.some((h) => t.includes(h));
};

/** How many of a claim's content words a sentence has to share before it counts as repeating it. */
const REPEAT_HITS = 3;

/** Does this sentence repeat this claim, in the one-sided way that can be decided here? */
function repeats(sentence: string, claim: string): boolean {
  const want = contentWords(claim);
  if (want.length < 2) return false;
  const have = contentWords(sentence);
  if (!have.length) return false;
  const hits = want.filter((w) => have.some((x) => shareStem(w, x))).length;
  if (hits < 2 || hits / want.length < 0.5) return false;
  return hits >= REPEAT_HITS || hits === want.length;
}

/** Path-looking tokens. Long enough to be real extensions, bounded so it cannot eat a whole sentence. */
const EXTS = "ts|tsx|mts|cts|js|jsx|mjs|cjs|py|rb|go|rs|java|kt|swift|php|cs|css|scss|sass|less|html|htm|json|jsonc|yml|yaml|toml|md|mdx|sql|sh|bash|ps1|vue|svelte|astro|txt|xml|svg|c|h|cpp|hpp|lock|env|cfg|ini|conf|example";
// A sentence ends with a period, so the trailing boundary cannot forbid one: `src/a.ts.` has to match
// `src/a.ts`. A name with two extensions (`dump.sql.bak`) is skipped by the guard below instead.
const FILE_RE = new RegExp(`(?<![\\w./@~-])([A-Za-z0-9_@][\\w@.-]*(?:/[\\w@.-]+)*\\.(?:${EXTS}))(?![\\w/@-])`, "g");

/**
 * Bare `something.js` that names a library or a runtime rather than a file. The project's own dependency
 * list is checked first, so a repo that depends on Vite does not get flagged for writing "vite.js" in
 * prose about it; the rest are the names that appear in prose about a stack.
 */
const KNOWN_SHORTHAND = new Set(["node", "deno", "bun", "npm", "next", "nuxt", "react", "vue", "svelte", "angular", "three", "d3", "express", "vite", "vitest", "jest", "playwright", "eslint", "prettier", "tailwind", "webpack", "rollup", "esbuild", "typescript", "postgres", "redis"]);

function pathCandidates(sentence: string, externals: Set<string>): string[] {
  const out: string[] = [];
  for (const m of sentence.matchAll(FILE_RE)) {
    const raw = m[1];
    const at = m.index ?? 0;
    // `foo.ts.bak` is one longer token, not a file named in prose.
    if (/^\.\w/.test(sentence.slice(at + raw.length))) continue;
    // A path inside a URL, and a path outside the project, are not claims about this repository's files.
    if (/https?:\/\/\S*$/.test(sentence.slice(Math.max(0, at - 16), at))) continue;
    if (raw.startsWith("/") || raw.startsWith("~") || raw.startsWith("../")) continue;
    const clean = raw.replace(/^\.\//, "");
    // A file-shaped word with no directory ("node.js"): skip the runtime and library shorthands, and
    // anything whose stem is one of this project's own dependencies.
    if (!clean.includes("/")) {
      const stem = clean.slice(0, clean.lastIndexOf(".")).toLowerCase();
      if (KNOWN_SHORTHAND.has(stem) || externals.has(stem)) continue;
    }
    // A domain-qualified path (`github.com/x.ts`) is not in this repository and not a claim about it.
    const first = clean.split("/")[0];
    if (clean.includes("/") && first.includes(".") && !first.startsWith(".")) continue;
    out.push(clean);
  }
  return out;
}

export interface ConclusionInput {
  synthesis: Synthesis;
  verification: Verification;
  /** The citation repair round, whose withdrawals are findings the record now says are not there. */
  repair?: RepairRound;
  index: RepoIndex;
  root: string;
  /** Shared across the mission: does this file exist on disk? */
  exists?: Map<string, boolean>;
}

/** The hour of arithmetic this whole file exists for: which sentences of the paragraph the record contradicts. */
export async function checkConclusion(input: ConclusionInput): Promise<ConclusionIssue[]> {
  const issues: ConclusionIssue[] = [];
  const known = new Set(input.index.files.map((f) => f.path));
  const externals = new Set(input.index.externals.map((e) => e.spec.replace(/^node:/, "").split("/")[0].toLowerCase()));
  const exists = input.exists ?? new Map<string, boolean>();
  const root = path.resolve(input.root);

  const withdrawn = (input.repair?.attempts ?? []).flatMap((a) => a.withdrawn.map((w) => ({ unit: a.unit, claim: w.claim, why: w.why })));

  const onDisk = async (rel: string): Promise<boolean> => {
    if (known.has(rel)) return true;
    if (exists.has(rel)) return exists.get(rel)!;
    let ok = false;
    try {
      await fs.access(path.join(root, rel));
      ok = true;
    } catch {
      ok = false;
    }
    exists.set(rel, ok);
    return ok;
  };

  const assertAgainst = (sentence: string): { kind: ConclusionKind; because: string; claim: CheckedClaim } | null => {
    for (const c of input.verification.rejected) {
      if (repeats(sentence, c.claim)) {
        return {
          kind: "reintroduced-rejection",
          claim: c,
          because: `the mission's own gate rejected this finding (${c.status}) and it is listed under "Rejected": ${c.claim}${c.detail ? ` — ${c.detail}` : ""}`,
        };
      }
    }
    for (const w of withdrawn) {
      if (repeats(sentence, w.claim)) {
        return {
          kind: "withdrawn-claim",
          claim: { unit: w.unit, role: "", claim: w.claim, path: "", quote: "", confidence: "medium", status: "quote-not-found" },
          because: `${w.unit} withdrew this claim on the repair pass rather than re-cite it, and the reason is on the record: ${w.why}`,
        };
      }
    }
    for (const c of input.verification.thin) {
      if (repeats(sentence, c.claim)) {
        return {
          kind: "thin-support",
          claim: c,
          because: `the quote for this finding is really at ${c.path}${c.lines ? `:${c.lines[0]}-${c.lines[1]}` : ""}, but it shares no wording with it — the mission labelled it THIN SUPPORT and said not to state it as established`,
        };
      }
    }
    return null;
  };

  for (const { field, item, text } of fieldTexts(input.synthesis)) {
    const lines = splitSentences(text);
    for (let i = 0; i < lines.length; i++) {
      for (let j = 0; j < lines[i].length; j++) {
        const sentence = lines[i][j];
        if (sentence.length < 12) continue;
        // The unverified list is where a rejected finding is supposed to end up, phrased as something to
        // check. Only the files it names are checked there.
        if (ASSERTIVE.includes(field) && !hedged(sentence)) {
          const hit = assertAgainst(sentence);
          if (hit) {
            issues.push({
              index: issues.length + 1,
              field,
              item,
              sentence: j,
              text: sentence,
              kind: hit.kind,
              because: hit.because,
              path: hit.claim.path || undefined,
              lines: hit.claim.lines,
            });
            continue; // one reason per sentence is enough to send it back
          }
        }
        for (const candidate of pathCandidates(sentence, externals)) {
          if (await onDisk(candidate)) continue;
          issues.push({
            index: issues.length + 1,
            field,
            item,
            sentence: j,
            text: sentence,
            kind: "unknown-file",
            path: candidate,
            because: `no file of that name is in this repository: it is not in the index of ${input.index.totals.files} file(s) and not on disk`,
          });
          break; // one unknown file per sentence: the sentence goes back as a unit
        }
      }
    }
  }
  return issues;
}

/** What a source said about each flagged sentence: a replacement, or a reason it cannot be said at all. */
export interface ConclusionFix {
  /** 1-based number of the issue this answers. */
  fixes: number;
  text?: string;
  why?: string;
}

/**
 * Put the answers back where the sentences were. A rewritten sentence keeps its place; a withdrawn one is
 * removed from the conclusion, and the reason for it is kept in the pass record instead — a sentence the
 * record contradicts is worse than a missing sentence, but silence is not free either, so it is never
 * silent. Whitespace inside a repaired field is re-rendered from its sentences.
 */
export function applyConclusionFixes(synthesis: Synthesis, issues: ConclusionIssue[], fixes: ConclusionFix[]): Synthesis {
  const byNumber = new Map(issues.map((i) => [i.index, i]));
  const replace = new Map<string, string>(); // `${field}|${item}|${sentence}` -> text
  const drop = new Set<string>();
  for (const f of fixes) {
    const issue = byNumber.get(f.fixes);
    if (!issue) continue;
    const key = `${issue.field}|${issue.item}|${issue.sentence}`;
    const text = f.text?.trim();
    if (text && text.length >= 8) replace.set(key, text);
    else if (f.why) drop.add(key);
  }
  if (!replace.size && !drop.size) return synthesis;

  const rebuild = (field: ConclusionField, item: number, text: string): string => {
    const lines = splitSentences(text);
    const out = lines
      .map((sentences, line) =>
        sentences
          .map((s, j) => {
            const key = `${field}|${item}|${j}`;
            if (drop.has(key)) return "";
            return replace.get(key) ?? s;
          })
          .filter(Boolean)
          .join(" ")
      )
      .filter((l) => l.trim().length)
      .join("\n");
    return out;
  };

  const out: Synthesis = { ...synthesis };
  out.answer = rebuild("answer", 0, synthesis.answer);
  out.firstAction = rebuild("firstAction", 0, synthesis.firstAction);
  out.risks = synthesis.risks.map((t, i) => rebuild("risks", i, t)).filter((t) => t.trim().length);
  out.unverified = synthesis.unverified.map((t, i) => rebuild("unverified", i, t)).filter((t) => t.trim().length);
  out.definitionOfDone = synthesis.definitionOfDone.map((t, i) => rebuild("definitionOfDone", i, t)).filter((t) => t.trim().length);
  // A conclusion that is empty because everything in it was withdrawn says so, rather than reading as a
  // blank page the reader has to interpret.
  if (!out.answer.trim()) out.answer = "(the leader withdrew every part of its conclusion that the record contradicted; see the evidence below)";
  if (!out.firstAction.trim()) out.firstAction = "Read the verified findings below and decide the first edit yourself.";
  return out;
}

export interface ConclusionRepairRecord {
  calls: number;
  sent: number;
  rewritten: number;
  withdrawn: { text: string; why: string }[];
  unaddressed: number;
  stillBroken: number;
  note: string;
  error?: string;
  ms: number;
}

const KIND_TEXT: Record<ConclusionKind, string> = {
  "reintroduced-rejection": "repeats a finding the gate deleted",
  "withdrawn-claim": "repeats a claim its own author withdrew",
  "thin-support": "states a THIN SUPPORT finding as established",
  "unknown-file": "names a file that is not in this repository",
};

/** The section that shows what the paragraph said and what the record says instead. */
export function renderConclusionCheck(issues: ConclusionIssue[]): string[] {
  const lines = [
    "",
    "## The conclusion, checked against the mission's own record",
    "The closing paragraph is not evidence, so nothing here decides whether it is right. What is checked is whether it contradicts the record this same run produced: whether a sentence asserts a finding the gate deleted (or one its own author withdrew), states a labelled THIN SUPPORT finding as established, or names a file that is not in the repository. Hedged wording that restates a rejection is correct usage and is not flagged.",
  ];
  if (!issues.length) {
    lines.push("- No sentence of the conclusion contradicted the record.");
  } else {
    lines.push(`- ${issues.length} sentence(s) contradict the record:`);
    for (const i of issues) {
      lines.push(`  - ${i.index}. [${i.kind}: ${KIND_TEXT[i.kind]}] ${i.field} — "${i.text.replace(/\s+/g, " ").slice(0, 240)}"`);
      lines.push(`      the record says: ${i.because.replace(/\s+/g, " ").slice(0, 400)}`);
    }
  }
  return lines;
}

/** The pass itself, when it ran: what went back, and what came back standing on the record. */
export function renderConclusionRepair(repair: ConclusionRepairRecord): string[] {
  const lines = [
    "",
    "## The conclusion repair pass (one second chance for a sentence the record contradicts)",
    `- The leader got its own ${repair.sent} flagged sentence(s) back with the record's own words — which finding the mission deleted, what its author said when withdrawing it, or that the file it named is not in this repository. ${repair.rewritten} were rewritten without contradicting the record, ${repair.withdrawn.length} were given up with a reason, ${repair.unaddressed} left unaddressed.`,
  ];
  if (repair.stillBroken) lines.push(`- ${repair.stillBroken} rewritten sentence(s) still contradict the record and are counted as such: a rewrite can put a new claim where the old one was, so the whole conclusion was re-checked, not just the answers.`);
  for (const w of repair.withdrawn) lines.push(`    - the leader gave up a sentence: "${w.text.replace(/\s+/g, " ").slice(0, 200)}" — ${w.why.replace(/\s+/g, " ").slice(0, 240)}`);
  if (repair.error) lines.push(`- The pass failed and the conclusion is as it was: ${repair.error.split("\n")[0]}`);
  lines.push("- Nothing else in the conclusion was touched: a repair answers the sentences it was handed, by number, and never rewrites a part that was already fine. Every rewrite went back through the same check at the same standard.");
  return lines;
}
